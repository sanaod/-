/**
 * تصفية وفلترة الكفايات بناءً على المادة والصف والموضوع ومصطلحات البحث
 */
export function filterCompetencies({
  allCompetencies,
  subject,
  grade,
  topic,
  searchQuery,
  categoryFilter = 'all',
  domainFilter = 'all',
}: {
  allCompetencies: CompetencyItem[];
  subject?: string;
  grade?: string;
  topic?: string;
  searchQuery?: string;
  categoryFilter?: 'all' | 'general' | 'subject_specific';
  domainFilter?: string;
}): CompetencyItem[] {
  return allCompetencies.filter((item) => {
    // 1. فلتر الفئة (عامة / خاصة)
    if (categoryFilter !== 'all' && item.category !== categoryFilter) {
      return false;
    }

    // 2. فلتر المجال
    if (domainFilter !== 'all' && item.domain !== domainFilter) {
      return false;
    }

    // 3. فلتر المادة
    if (subject && subject.trim() !== '') {
      const cleanSub = subject.trim();
      const isGeneral = item.category === 'general' || item.subject.includes('جميع');
      const matchesSubject = item.subject.toLowerCase().includes(cleanSub.toLowerCase()) ||
                             cleanSub.toLowerCase().includes(item.subject.toLowerCase());
      if (!isGeneral && !matchesSubject) {
        return false;
      }
    }

    // 4. فلتر الصف
    if (grade && grade.trim() !== '') {
      const cleanGrade = grade.trim();
      const matchesAllGrades = item.grades.includes('جميع الصفوف');
      const matchesSpecificGrade = item.grades.some((g) =>
        g.includes(cleanGrade) || cleanGrade.includes(g)
      );
      if (!matchesAllGrades && !matchesSpecificGrade) {
        return false;
      }
    }

    // 5. فلتر الموضوع إذا وجد
    if (topic && topic.trim() !== '') {
      const cleanTopic = topic.trim().toLowerCase();
      const inTopics = item.topics.some((t) => t.toLowerCase().includes(cleanTopic));
      const inTitle = item.title.toLowerCase().includes(cleanTopic);
      const inStatement = item.statement.toLowerCase().includes(cleanTopic);
      // إذا لم يكن عاماً جداً، نفضل المطابقة
    }

    // 6. فلتر كلمة البحث
    if (searchQuery && searchQuery.trim() !== '') {
      const q = searchQuery.trim().toLowerCase();
      const matchInTitle = item.title.toLowerCase().includes(q);
      const matchInStatement = item.statement.toLowerCase().includes(q);
      const matchInDomain = item.domainLabel.toLowerCase().includes(q);
      const matchInSubject = item.subject.toLowerCase().includes(q);
      const matchInCode = item.code.toLowerCase().includes(q);
      const matchInIndicators = item.performanceIndicators.some(
        (ind) => ind.statement.toLowerCase().includes(q) || ind.observableAction.toLowerCase().includes(q)
      );
      const matchInSituations = item.learningSituations.some(
        (sit) => sit.title.toLowerCase().includes(q) || sit.contextDescription.toLowerCase().includes(q)
      );

      if (!matchInTitle && !matchInStatement && !matchInDomain && !matchInSubject && !matchInCode && !matchInIndicators && !matchInSituations) {
        return false;
      }
    }

    return true;
  });
}

/**
 * حساب نسبة تغطية الكفايات المقررة خلال الفصل الدراسي
 * Visual Semester Competency Coverage Analysis
 */
export function calculateSemesterCompetencyCoverage({
  plans,
  allCompetencies,
  targetSubject,
  targetGrade,
}: {
  plans: LessonPlan[];
  allCompetencies: CompetencyItem[];
  targetSubject?: string;
  targetGrade?: string;
}): CompetencyCoverageReport {
  // تصفية الكفايات المستهدفة لهذا المستوى (المادة والصف المحددان)
  const targetCompetencies = allCompetencies.filter((item) => {
    // الكفايات العامة تهم كل المباحث
    if (item.category === 'general') {
      if (targetGrade && targetGrade.trim() !== '') {
        const matchesAll = item.grades.includes('جميع الصفوف');
        const matchesGrade = item.grades.some((g) => g.includes(targetGrade) || targetGrade.includes(g));
        return matchesAll || matchesGrade;
      }
      return true;
    }

    // الكفايات التخصصية: يجب أن تطابق المادة
    if (targetSubject && targetSubject.trim() !== '') {
      const subMatch = item.subject.toLowerCase().includes(targetSubject.toLowerCase()) ||
                       targetSubject.toLowerCase().includes(item.subject.toLowerCase());
      if (!subMatch) return false;
    }

    if (targetGrade && targetGrade.trim() !== '') {
      const matchesAll = item.grades.includes('جميع الصفوف');
      const matchesGrade = item.grades.some((g) => g.includes(targetGrade) || targetGrade.includes(g));
      return matchesAll || matchesGrade;
    }

    return true;
  });

  const totalTargetCompetencies = targetCompetencies.length > 0 ? targetCompetencies.length : allCompetencies.length;
  const targetSet = targetCompetencies.length > 0 ? targetCompetencies : allCompetencies;

  // فحص الكفايات المشمولة في خطط المعلم
  const coveredCompetencyIdSet = new Set<string>();

  // تصفية الخطط للمادة والصف إن تم تحديدهما
  const filteredPlans = plans.filter((p) => {
    if (targetSubject && targetSubject.trim() !== '' && p.header.subject) {
      if (!p.header.subject.toLowerCase().includes(targetSubject.toLowerCase()) &&
          !targetSubject.toLowerCase().includes(p.header.subject.toLowerCase())) {
        return false;
      }
    }
    if (targetGrade && targetGrade.trim() !== '' && p.header.grade) {
      if (!p.header.grade.includes(targetGrade) && !targetGrade.includes(p.header.grade)) {
        return false;
      }
    }
    return true;
  });

  filteredPlans.forEach((plan) => {
    // 1. في section1.integrativeCompetencies
    const planComps = plan.section1?.integrativeCompetencies || [];
    planComps.forEach((comp: { title: string; description: string }) => {
      const textToSearch = `${comp.title} ${comp.description}`.toLowerCase();
      targetSet.forEach((c) => {
        if (
          textToSearch.includes(c.title.toLowerCase()) ||
          textToSearch.includes(c.code.toLowerCase()) ||
          (c.title.length > 5 && textToSearch.includes(c.title.substring(0, 10).toLowerCase()))
        ) {
          coveredCompetencyIdSet.add(c.id);
        }
      });
    });

    // 2. في نصوص المراحل والأنشطة والتقويم
    const fullPlanText = JSON.stringify(plan).toLowerCase();
    targetSet.forEach((c) => {
      if (
        fullPlanText.includes(c.code.toLowerCase()) ||
        fullPlanText.includes(c.title.toLowerCase())
      ) {
        coveredCompetencyIdSet.add(c.id);
      }
    });
  });

  const coveredCount = coveredCompetencyIdSet.size;
  const coveragePercentage = totalTargetCompetencies > 0
    ? Math.min(100, Math.round((coveredCount / totalTargetCompetencies) * 100))
    : 0;

  // تفصيل حسب مجالات الكفايات العامة
  const domains: { domain: GeneralCompetencyDomain; domainLabel: string }[] = [
    { domain: 'communication', domainLabel: 'التواصل والاتصال' },
    { domain: 'critical_thinking', domainLabel: 'التفكير الناقد وحل المشكلات' },
    { domain: 'creativity', domainLabel: 'الإبداع والابتكار' },
    { domain: 'participation_responsibility', domainLabel: 'المشاركة والمسؤولية' },
  ];

  const generalCompetenciesCoverage = domains.map(({ domain, domainLabel }) => {
    const domainComps = targetSet.filter((c) => c.domain === domain);
    const domainCovered = domainComps.filter((c) => coveredCompetencyIdSet.has(c.id)).length;
    return {
      domain,
      domainLabel,
      total: domainComps.length,
      covered: domainCovered,
      percentage: domainComps.length > 0 ? Math.round((domainCovered / domainComps.length) * 100) : 0,
    };
  });

  // تفصيل كفايات المادة التخصصية
  const subjectComps = targetSet.filter((c) => c.category === 'subject_specific');
  const subjectCovered = subjectComps.filter((c) => coveredCompetencyIdSet.has(c.id)).length;

  const subjectCompetenciesCoverage = {
    subject: targetSubject || 'الكفايات التخصصية للمبحث',
    total: subjectComps.length,
    covered: subjectCovered,
    percentage: subjectComps.length > 0 ? Math.round((subjectCovered / subjectComps.length) * 100) : 0,
  };

  const uncoveredCompetencies = targetSet.filter((c) => !coveredCompetencyIdSet.has(c.id));

  return {
    totalTargetCompetencies,
    coveredCompetenciesCount: coveredCount,
    coveragePercentage,
    generalCompetenciesCoverage,
    subjectCompetenciesCoverage,
    coveredCompetencyIds: Array.from(coveredCompetencyIdSet),
    uncoveredCompetencies,
    plansAnalyzedCount: filteredPlans.length,
  };
}
